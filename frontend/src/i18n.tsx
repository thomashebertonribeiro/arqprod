export type Dict = (typeof DICTS)['pt-BR'];

export interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: keyof Dict, vars?: Record<string, string | number>) => string;
  formatCurrency: (valor: string, moeda: string) => string;
  formatDate: (iso: string) => string;
}

const LangContext = createContext<I18nValue>({
  lang: 'pt-BR',
  setLang: () => undefined,
  t: (key) => key as string,
  formatCurrency: (v) => v,
  formatDate: (d) => d,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      return saved === 'en' ? 'en' : 'pt-BR';
    } catch {
      return 'pt-BR';
    }
  });

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage indisponível */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback<I18nValue['t']>(
    (key, vars) => {
      let s = DICTS[lang][key] ?? DICTS['pt-BR'][key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.split(`{${k}}`).join(String(v));
        }
      }
      return s;
    },
    [lang],
  );

  const formatCurrency = useCallback(
    (valor: string, moeda: string) =>
      new Intl.NumberFormat(lang === 'pt-BR' ? 'pt-BR' : 'en-US', {
        style: 'currency',
        currency: moeda,
      }).format(Number(valor)),
    [lang],
  );

  const formatDate = useCallback(
    (iso: string) =>
      new Date(iso).toLocaleDateString(lang === 'pt-BR' ? 'pt-BR' : 'en-US'),
    [lang],
  );

  return (
    <LangContext.Provider value={{ lang, setLang, t, formatCurrency, formatDate }}>
      {children}
    </LangContext.Provider>
  );
}

export function useI18n() {
  return useContext(LangContext);
}